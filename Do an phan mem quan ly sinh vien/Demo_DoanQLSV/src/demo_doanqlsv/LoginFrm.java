    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        try {
        Connection conn = dao.DatabaseConnection.openConnection();
        if (conn == null) {
            JOptionPane.showMessageDialog(this, "Không thể kết nối CSDL!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        String sql = "SELECT * FROM tblUser WHERE fldUser=? AND fldPassword=?";
        PreparedStatement pstmt = conn.prepareStatement(sql);
        pstmt.setString(1, txtUser.getText().trim());
        pstmt.setString(2, new String(txtPass.getPassword()));
        
       ResultSet rs = pstmt.executeQuery();
        
        if(rs.next()){
            JOptionPane.showMessageDialog(this, "Đăng nhập thành công!");
            this.dispose(); 
    
            new StudentFrm().setVisible(true);
          } else {
        }
        
        rs.close();
        pstmt.close();
        conn.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnLoginActionPerformed

